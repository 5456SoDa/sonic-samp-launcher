	private int Clamp255(string s)
	{
		int result;
		if (!int.TryParse(s.Trim(), out result))
		{
			result = 0;
		}
		if (result < 0)
		{
			result = 0;
		}
		if (result > 255)
		{
			result = 255;
		}
		return result;
	}

